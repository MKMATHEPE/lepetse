// Read trusted local prototype data; never fetch or evaluate remote scripts.
// Generates a versioned, reviewable data migration. Do not regenerate an applied
// migration in a shared database; create a new migration for later source updates.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const backend = path.resolve(__dirname, '..');
const dist = path.resolve(backend, '../dist');
const files = ['products.js','imported-products.js','price-references.js','school-lists.js','curro-data.js','curro-school.js'];
const context = vm.createContext({});
const hashes = {};
for (const file of files) {
  const code = fs.readFileSync(path.join(dist, file), 'utf8');
  hashes[file] = crypto.createHash('sha256').update(code).digest('hex');
  vm.runInContext(code, context, {timeout: 3000, filename: file});
}
const data = JSON.parse(vm.runInContext(`JSON.stringify({products,retiredProducts,priceReferences,schoolGradeLists,curroNames,curroLists,importedExistingRows})`, context));
const sql = ['-- Snapshot of existing prototype data. Generated by scripts/generate-import.cjs.',
  '-- No selling prices are approved; no customers, orders or personal data are imported.'];
const q = value => value == null ? 'NULL' : "'" + String(value).replaceAll("'", "''") + "'";
const json = value => q(JSON.stringify(value)) + '::jsonb';
const productId = id => `(SELECT id FROM product WHERE legacy_id=${q(id)})`;
const categories = {paper:'Paper & printing',pens:'Writing essentials',files:'Files & office supplies',books:'Books & notebooks',pack:'School stationery packs',art:'Art & craft',ruler:'Rulers & geometry',calc:'Calculators'};
for (const [code, name] of Object.entries(categories)) sql.push(`INSERT INTO category(code,name) VALUES (${q(code)},${q(name)}) ON CONFLICT (code) DO NOTHING;`);
const all = [...data.products, ...data.retiredProducts];
if (new Set(all.map(p=>p.id)).size !== all.length) throw Error('Duplicate product IDs');
const byId = new Map(all.map(p=>[p.id,p]));
for (const name of new Set(all.map(p=>p.brand).filter(b=>b && b !== 'To be confirmed'))) sql.push(`INSERT INTO brand(name) VALUES (${q(name)}) ON CONFLICT (name) DO NOTHING;`);
for (const p of all) {
  if (!categories[p.category]) throw Error('Unknown category: ' + p.category);
  const active = data.products.some(x=>x.id===p.id);
  const brand = p.brand && p.brand !== 'To be confirmed' ? `(SELECT id FROM brand WHERE name=${q(p.brand)})` : 'NULL';
  // Pack quantities remain unknown unless explicitly verified later; wording is retained.
  sql.push(`INSERT INTO product(legacy_id,name,description,brand_id,category_id,ordering_unit,specifications,active,source_snapshot) VALUES (${q(p.id)},${q(p.name)},${q(p.summary)},${brand},(SELECT id FROM category WHERE code=${q(p.category)}),${q(p.unit)},${json(p.specs||{})},${active},${json(p)}) ON CONFLICT (legacy_id) DO NOTHING;`);
  if (p.image) {
    if (!fs.existsSync(path.join(dist,p.image))) throw Error('Missing image: '+p.image);
    const imageMatch = p.imageStatus==='matched'||(!p.imageStatus&&p.supplierReference?.imageSourceUrl) ? 'matched' : 'reference';
    sql.push(`INSERT INTO product_image(product_id,asset_path,alt_text,match_status,source_url,source_snapshot) SELECT ${productId(p.id)},${q(p.image)},${q(p.name)},${q(imageMatch)},${q(p.imageReference?.url||p.supplierReference?.imageSourceUrl)},${json({imageType:p.imageType,imageReference:p.imageReference,supplierReference:p.supplierReference})} WHERE NOT EXISTS (SELECT 1 FROM product_image WHERE product_id=${productId(p.id)} AND asset_path=${q(p.image)});`);
  }
  const s = p.supplierReference || (p.catalogueImport ? {name:p.catalogueImport.supplier} : null);
  if (s) {
    sql.push(`INSERT INTO supplier(name) VALUES (${q(s.name)}) ON CONFLICT (name) DO NOTHING;`);
    sql.push(`INSERT INTO supplier_product(supplier_id,product_id,supplier_sku,source_url,checked_at,source_document,source_row,source_snapshot) VALUES ((SELECT id FROM supplier WHERE name=${q(s.name)}),${productId(p.id)},${q(s.sku)},${q(s.url)},${s.checkedOn?q(s.checkedOn+'T00:00:00Z'):'NULL'},${q(p.catalogueImport?.source)},${p.catalogueImport?.row||'NULL'},${json({supplierReference:p.supplierReference,catalogueImport:p.catalogueImport})}) ON CONFLICT (supplier_id,product_id) DO NOTHING;`);
  }
}
for (const p of all) {
  const replacement = p.replacementId || data.products.find(x=>x.replacementFor?.includes(p.id))?.id;
  if (replacement) {
    if (!byId.has(replacement)) throw Error('Missing replacement: '+replacement);
    sql.push(`INSERT INTO product_replacement VALUES (${productId(p.id)},${productId(replacement)}) ON CONFLICT DO NOTHING;`);
  }
}
let referenceCount = 0;
for (const [id,r] of Object.entries(data.priceReferences)) {
  if (!byId.has(id)) throw Error('Price refers to missing product: '+id);
  if (!Number.isInteger(r.amountMinor)||r.amountMinor<0||r.currency!=='ZAR') throw Error('Invalid price reference');
  sql.push(`INSERT INTO product_price_reference(product_id,retailer,amount,currency,source_url,checked_on,source_snapshot) VALUES (${productId(id)},${q(r.retailer)},${(r.amountMinor/100).toFixed(2)},'ZAR',${q(r.sourceUrl)},${q(r.checkedOn)},${json(r)}) ON CONFLICT (product_id,retailer,source_url) DO NOTHING;`);
  referenceCount++;
}
// Preserve the six catalogue spreadsheet entries that link to existing products.
for (const row of data.importedExistingRows) {
  const name='Packaging & Stationery Distributors';
  sql.push(`INSERT INTO supplier(name) VALUES (${q(name)}) ON CONFLICT DO NOTHING;`);
  sql.push(`INSERT INTO supplier_product(supplier_id,product_id,source_document,source_row,source_snapshot) VALUES ((SELECT id FROM supplier WHERE name=${q(name)}),${productId(row.productId)},'Stationery_Product_Catalogue.xlsx',${row.row},${json(row)}) ON CONFLICT (supplier_id,product_id) DO NOTHING;`);
}
const schools = [{slug:'glenanda-primary',name:'Glenanda Primary'},{slug:'curro-serengeti',name:'Curro Serengeti'}];
for (const s of schools) sql.push(`INSERT INTO school(slug,name) VALUES (${q(s.slug)},${q(s.name)}) ON CONFLICT (slug) DO NOTHING;`);
let listCount=0, itemCount=0;
function list(slug,grade,year,source) {
  sql.push(`INSERT INTO school_list(school_id,grade,academic_year,source_document,status) SELECT id,${q(grade)},${year||'NULL'},${q(source)},'published' FROM school WHERE slug=${q(slug)} ON CONFLICT DO NOTHING;`);
  listCount++;
  return `(SELECT l.id FROM school_list l JOIN school s ON s.id=l.school_id WHERE s.slug=${q(slug)} AND grade=${q(grade)} AND academic_year IS NOT DISTINCT FROM ${year||'NULL'} AND version=1)`;
}
function item(listId, key, subject, name, qty, unit, proposed, notes, optional, reuse, raw, conversion={required:1,supplied:1}) {
  if (proposed && !byId.has(proposed)) throw Error('School match missing: '+proposed);
  sql.push(`INSERT INTO school_list_item(school_list_id,source_key,subject,requested_description,quantity_per_learner,requested_unit,proposed_product_id,replacement_notes,optional,reuse_existing,display_order,source_snapshot,conversion_required,conversion_supplied) VALUES (${listId},${q(key)},${q(subject)},${q(name)},${qty??'NULL'},${q(unit)},${proposed?productId(proposed):'NULL'},${q(notes)},${!!optional},${!!reuse},${itemCount++},${json(raw)},${conversion.required},${conversion.supplied}) ON CONFLICT (school_list_id,source_key) DO NOTHING;`);
}
for (const [grade,lines] of Object.entries(data.schoolGradeLists)) {
  const id=list('glenanda-primary',grade,null,'Glenanda_Primary_Stationery_Grades_R_to_7.xlsx');
  for (const line of lines) {
    const p = vm.runInContext(`schoolProduct(${JSON.stringify(line.key)})`,context);
    if (!p) throw Error('Unresolved Glenanda requirement: '+line.key);
    const conversion = vm.runInContext(`schoolConversion(${JSON.stringify(line.key)})`,context);
    item(id,line.key,null,line.original,line.quantity,line.unit,p.id,line.difference,false,false,line,conversion);
  }
}
for (const [grade,d] of Object.entries(data.curroLists)) {
  const id=list('curro-serengeti',grade,2027,`school-lists/curro-serengeti-grade-${grade}-2027.pdf`);
  for (const [subject,counts] of [[null,d.general],...Object.entries(d.subjects)]) {
    for (const [index,quantity] of Object.entries(counts)) {
      const unit=index==='2'?'Pack of 10':index==='10'?'Pack of 3 or 4':'Each';
      const reuse=grade==='12' && subject==='English Home Language' && index==='5';
      item(id,`${subject||'general'}:core:${index}`,subject,data.curroNames[index],quantity,unit,null,reuse?'School prefers reusing Grade 10–11 English books.':null,false,reuse,{index,quantity,subject});
    }
  }
  for (const [subject,names] of Object.entries(d.extras)) {
    names.forEach((name,index)=>{
      const match=name.match(/^(\d+) × /);
      const qty=match?Number(match[1]):subject==='Engineering Graphics and Design'?1:null;
      item(id,`${subject}:extra:${index}`,subject,name.replace(/^\d+ × /,''),qty,'Each / set as specified',null,null,/optional/i.test(name),false,{name,subject,index});
    });
  }
}
const output=path.join(backend,'src/main/resources/db/migration/V3__import_prototype_catalogue_and_schools.sql');
fs.writeFileSync(output,sql.join('\n')+'\n');
const report={sourceFiles:hashes,activeProducts:data.products.length,inactiveLegacyRequirements:data.retiredProducts.length,products:all.length,priceReferences:referenceCount,schools:schools.length,schoolLists:listCount,schoolItems:itemCount,approvedSellingPrices:0};
fs.writeFileSync(path.join(backend,'import-manifest.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
